CREATE TABLE conversation_pins (
    id VARCHAR(255) PRIMARY KEY,
    conversation_id VARCHAR(255) NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    text TEXT NOT NULL,
    ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision >= 1),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    source_conversation_id VARCHAR(255),
    source_message_id VARCHAR(255),
    CONSTRAINT conversation_pin_source_pair CHECK ((source_conversation_id IS NULL) = (source_message_id IS NULL)),
    CONSTRAINT conversation_pin_order UNIQUE (conversation_id, ordinal)
);

-- A receipt survives deletion of its pin. It stores no text and is not copied on fork.
-- Actor is provenance, intentionally not a cascading FK. Conversation deletion removes the catalog and receipts.
CREATE TABLE conversation_pin_creations (
    conversation_id VARCHAR(255) NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    actor_id VARCHAR(255) NOT NULL,
    creation_key VARCHAR(512) NOT NULL,
    payload_sha256 VARCHAR(64) NOT NULL,
    pin_id VARCHAR(255) NOT NULL,
    PRIMARY KEY (conversation_id, actor_id, creation_key)
);
